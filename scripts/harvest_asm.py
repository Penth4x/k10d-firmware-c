#!/usr/bin/env python3
"""harvest_asm.py <function_name> [more names...]

Make a function fcc CANNOT faithfully recompile into byte-faithful assembler.

Some decompiled functions read incoming caller registers (r0_in / caller_rN / unaff_rN) or
set the stack pointer or never return — fcc models those reads as uninitialised locals and
invents a frame, producing code that diverges from the original (see BESTIARY B-8). For such a
function the only faithful implementation is the original bytes themselves. This tool emits them
as a SOFTUNE FASM911S source under cpu/gen/, with every `ldi:32 #addr` that targets a KNOWN
recompiled function rewritten to `LDI:32 #_symbol` so calls/jumps still reach the recompiled tree
(the data-only-harvest invariant: no original CODE address is ever executed), and all other bytes
emitted as `.DATA.B`. It then renames the decompiled .c to .c.handasm so it stops compiling a
duplicate symbol. cpu/build.sh assembles every cpu/gen/*.asm, so the function is picked up with no
further wiring.

Verify each result: a function with a relative branch to OUTSIDE its own body, or an ldi:32 that
loads a function address only as DATA, needs a human look (flagged in the output).
"""
import os, re, sys, struct, subprocess

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC  = os.path.join(ROOT, "cpu", "src")
GEN  = os.path.join(ROOT, "cpu", "gen")
FW   = open("/home/memorai/k10d-re/FWDC162B.BIN", "rb").read()
BASE = 0x10000000

def r16(a): o=a-BASE; return (FW[o]<<8)|FW[o+1]
def r32(a): o=a-BASE; return struct.unpack(">I", FW[o:o+4])[0]

# VA -> function name, from every @k10d header in the source tree
VA2NAME = {}
NAME2SRC = {}
hdr = re.compile(r'@k10d\s+([A-Za-z0-9_]+)\s+@\s+(0x[0-9a-f]+)')
for dp,_,fns in os.walk(SRC):
    for fn in fns:
        if not fn.endswith(".c"): continue
        p = os.path.join(dp, fn)
        try: t = open(p, encoding="latin-1").read(4000)
        except OSError: continue
        m = hdr.search(t)
        if m:
            va = int(m.group(2), 16)
            VA2NAME[va] = m.group(1)
            NAME2SRC[m.group(1)] = p
FUNC_VAS = sorted(VA2NAME)

def extent(va):
    import bisect
    i = bisect.bisect_right(FUNC_VAS, va)
    return FUNC_VAS[i] if i < len(FUNC_VAS) else va+0x400

def is_ldi32(w): return ((w>>4)&0xFFF) == 0x9F8     # ldi:32 #imm32, rI

def harvest(name, start=None, end=None):
    if name not in NAME2SRC:
        print(f"!! {name}: no @k10d source found"); return False
    va = start if start is not None else next(v for v,n in VA2NAME.items() if n==name)
    if end is None:
        end = extent(va)
    out = [f"; {name} @ {va:#x} .. {end:#x} — byte-faithful harvest (fcc-can't-recompile; B-8).",
           f"; Generated by scripts/harvest_asm.py. ldi:32 loads of known functions are symbolic;",
           f"; every other byte is literal. Verify branches stay inside the body.",
           "\t.SECTION\tCODE, CODE, ALIGN=2",
           f"\t.GLOBAL\t_{name}",
           f"_{name}:"]
    warns = []
    pc = va
    while pc < end:
        w = r16(pc)
        if is_ldi32(w) and pc+6 <= end:
            ri = w & 0xF
            imm = r32(pc+2)
            if imm in VA2NAME:                        # code address -> symbolic
                out.append(f"\tLDI:32\t#_{VA2NAME[imm]}, R{ri}")
                pc += 6; continue
            # else: data address (rodata/SDRAM/vtable) -> literal bytes
        b = [FW[(pc-BASE)+k] for k in range(2)]
        out.append("\t.DATA.B\t" + ",".join(f"0x{x:02x}" for x in b))
        pc += 2
    out.append("\t.END")
    os.makedirs(GEN, exist_ok=True)
    ap = os.path.join(GEN, f"{name}.asm")
    open(ap, "w").write("\n".join(out)+"\n")
    # exclude from the C build EVERY map-fragment whose VA falls inside [va,end): a mis-split
    # function is harvested whole, so its interior fragments must stop emitting their own symbols.
    subsumed = []
    for fva, fname in sorted(VA2NAME.items()):
        if va <= fva < end:
            cp = NAME2SRC.get(fname, "")
            if cp.endswith(".c") and os.path.exists(cp):
                os.rename(cp, cp+".handasm"); subsumed.append(fname)
    print(f"ok {name}: {va:#x}..{end:#x} ({end-va} bytes) -> cpu/gen/{name}.asm")
    print(f"   subsumed fragments ({len(subsumed)}): {', '.join(subsumed)}")
    return True

if __name__ == "__main__":
    # harvest_asm.py <name>                 (extent from the function map)
    # harvest_asm.py <name> <start> <end>   (explicit whole-function extent, overriding a mis-split)
    if len(sys.argv) == 4:
        ok = harvest(sys.argv[1], int(sys.argv[2],16), int(sys.argv[3],16))
    elif len(sys.argv) >= 2:
        ok = all(harvest(n) for n in sys.argv[1:])
    else:
        print(__doc__); sys.exit(1)
    sys.exit(0 if ok else 1)
