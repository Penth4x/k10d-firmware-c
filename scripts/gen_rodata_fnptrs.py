#!/usr/bin/env python3
"""gen_rodata_fnptrs.py — relocate un-relocated function pointers in harvested rodata.

See scripts/find_rodata_fnptrs.py for the problem. The overlay keeps original rodata byte-identical
except recognised vtables; dispatch/state tables Ghidra didn't tag as vtables keep ORIGINAL code
addresses, so packed code calling through them runs un-relocated original code and derails.

This emits cpu/gen/rodata_fnptrs.asm: one tiny CONST section per un-relocated function-pointer word,
placing the PACKED symbol at that exact rodata address (LOCATE=<addr>). Only the fn-ptr words change
(no table-boundary guessing); the linker resolves each symbol to its packed address and overlay_fr.py
overlays the S-records. Stock calls these functions at their original addresses; relocating makes the
candidate call the identical recompiled (packed) functions, so behaviour matches stock.

IMPORTANT — do NOT relocate blindly. A blanket relocation of every rodata word equal to a function
origVA REGRESSES boot: some words are DATA that merely happens to equal a function address (keys,
constants, non-call tables), and relocating them corrupts early boot (seen crashing
initialize_seven_subobject_container). So relocation is gated on CONFIRMED_TABLES — address ranges of
dispatch tables proven reached-and-derailing by the emulator (FRN_NO_REBOOT trace). Add a range only
after a trace shows packed code calling an original fn-ptr from it. The finder
(scripts/find_rodata_fnptrs.py) lists all candidates; this generator relocates only the confirmed set.

cpu/build.sh step [2] globs cpu/gen/*.asm, so the file is picked up with no further wiring.
Idempotent: regenerate any time. Run from the repo root.
"""
# Confirmed reached-and-derailing dispatch tables (half-open [lo,hi) byte ranges). Add entries only
# after an emulator trace proves packed code dispatches through an original fn-ptr in the range.
CONFIRMED_TABLES = [
    (0x105a7e24, 0x105a7f64),   # cpucom / ui_task5 ({value,handler}) table -> ui_task5_body etc. (blocker #4)
]
import os, re, struct, glob, bisect
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FW   = open("/home/memorai/k10d-re/FWDC162B.BIN","rb").read()
BASE = 0x10000000
CODE_LO, CODE_HI = 0x10008000, 0x10622400
def r32(a): return struct.unpack(">I", FW[a-BASE:a-BASE+4])[0]

va2name = {}
hdr = re.compile(r'@k10d\s+(\w+)\s+@\s+0x([0-9a-fA-F]{8})')
for p in glob.glob(ROOT+"/cpu/src/**/*.c", recursive=True):
    m = hdr.search(open(p, encoding="latin-1").read(300))
    if m: va2name[int(m.group(2),16)] = m.group(1)

# ranges already covered by vtables.asm (don't double-emit)
vt = []; cur = None
for line in open(ROOT+"/cpu/gen/vtables.asm", encoding="latin-1"):
    m = re.search(r'\.SECTION\s+VT_([0-9a-fA-F]+),\s*CONST,\s*LOCATE=0x([0-9a-fA-F]+)', line)
    if m:
        if cur: vt.append(cur)
        cur = [int(m.group(2),16), int(m.group(2),16)]
    elif cur is not None and re.search(r'\.DATA\.L', line):
        cur[1] += 4
if cur: vt.append(cur)
vt.sort(); vlo = [v[0] for v in vt]
def in_vt(a):
    i = bisect.bisect_right(vlo, a) - 1
    return i >= 0 and vt[i][0] <= a < vt[i][1]

out = ["; rodata function-pointer relocations (generated by scripts/gen_rodata_fnptrs.py).",
       "; One CONST word per un-relocated fn-ptr in a CONFIRMED-reached dispatch table: places the",
       "; PACKED symbol at the original rodata address so packed code dispatching through the table",
       "; reaches the recompiled function. Gated on CONFIRMED_TABLES (emulator-proven) — NOT a blanket",
       "; relocation (that regresses boot; see the module docstring)."]
n = 0
for (tlo, thi) in CONFIRMED_TABLES:
    for a in range(tlo & ~3, thi, 4):
        v = r32(a)
        if CODE_LO <= v < CODE_HI and v in va2name and not in_vt(a):
            out.append(f"\t.SECTION\tFP_{a:08x}, CONST, LOCATE=0x{a:08x}")
            out.append(f"\t.DATA.L\t_{va2name[v]}")
            n += 1
out.append("\t.END")
open(ROOT+"/cpu/gen/rodata_fnptrs.asm","w").write("\n".join(out)+"\n")
print(f"wrote cpu/gen/rodata_fnptrs.asm: {n} function-pointer relocations")
