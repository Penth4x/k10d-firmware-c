#!/usr/bin/env python3
"""struct_width_check.py -- recover struct FIELD widths from the ORIGINAL firmware's actual
`this`-relative store/load widths, and reconcile them against the generated cpu/include/structs.h.

WHY: structs.h is generated by harness2/struct_recover.py, which takes the MAX width Ghidra's
FillOutStructureHelper *inferred* per field across a class's ctor/dtor/vtable members. That
inference is wrong wherever Ghidra guessed from context instead of a real access -- it types a
halfword field as uint8 (too narrow -> fcc emits stb, truncating a 16-bit store) or a byte field
as uint32 (too wide -> fcc emits a word store, clobbering the adjacent bytes the original left
untouched). This is the B-12s class in DECOMPILE_FINDINGS.

GROUND TRUTH: the original FWDC162B.BIN. For every function whose first parameter is a known
`cls_XXXX *` (from the type-recovery propagation cache + evident types + the cls_<vt>_* files),
disassemble it and record the width of every `this`-relative access:
    st/sth/stb  ri,@(r13,rj)   (op 0x10/0x11/0x12)   -> 32/16/8, EA = r13 + rj
    st/sth/stb  ri,@rj         (op 0x14/0x15/0x16)   -> 32/16/8, EA = rj
    ld/lduh/ldub @(r13,rj),ri  (op 0x00/0x01/0x02)   -> 32/16/8
    ld/lduh/ldub @rj,ri        (op 0x04/0x05/0x06)   -> 32/16/8
where one of the address operands is `this` (param_1, enters in r4; tracked through mov/addn) and
the other is a known immediate offset (r13 is loaded by ldi:8 #off,r13). The field's true width is
the MAX access width observed at that offset. Fields are then reconciled with structs.h.

  struct_width_check.py [--class cls_XXXX ...] [--all] [--write]
     default: report the flagged classes only (the B-12s backlog).
     --all:   probe every class that has a struct + >=1 known accessor.
     --write: rewrite the affected structs in cpu/include/structs.h (padding inserted to keep every
              following field at its offset), and `touch` the member .c files so the incremental
              build (keyed on .c mtime, not headers) rebuilds them.
"""
import os, re, sys, glob, json, struct, argparse

ROOT    = "/home/memorai/k10d-firmware-c"
STRUCTS = os.path.join(ROOT, "cpu/include/structs.h")
RESOLVED = os.path.join(ROOT, "cleanup/resolved_types.json")
FW      = open("/home/memorai/k10d-re/FWDC162B.BIN", "rb").read()
BASE    = 0x10000000

# flagged classes from the B-12s findings backlog (the "known width issues")
FLAGGED = ["cls_105b3cdc", "cls_105fa8e4", "cls_105b3ee0", "cls_105a6f3c", "cls_105a5c2c"]

sys.path.insert(0, os.path.join(ROOT, "scripts"))

# ---------------------------------------------------------------- firmware access
def r16(a): o = a - BASE; return (FW[o] << 8) | FW[o + 1]
def sx8(v): return v - 0x100 if v & 0x80 else v

STORE = {0x10: 32, 0x11: 16, 0x12: 8, 0x14: 32, 0x15: 16, 0x16: 8}   # @(r13,rj) / @rj
LOAD  = {0x00: 32, 0x01: 16, 0x02: 8, 0x04: 32, 0x05: 16, 0x06: 8}
INDEXED = {0x10, 0x11, 0x12, 0x00, 0x01, 0x02}     # @(r13,rj): EA = r13 + rj
DIRECT  = {0x14, 0x15, 0x16, 0x04, 0x05, 0x06}     # @rj:       EA = rj

def probe_this_accesses(va, cap=0x800):
    """Linear-scan a function, tracking which registers hold `this`+k (param_1 enters r4) and which
    hold a known immediate. Yield (field_offset, width, is_store) for every this-relative access.

    `this` is r4 under the FR OOP ABI. In a constructor the object is either the passed param (r4)
    or a freshly heap_alloc'd block whose pointer is the call's RETURN value -- also r4. So after any
    call returns we re-establish r4 = this+0 (the delay slot of a call:d may transiently load an
    alloc-size arg into r4; the re-seed lands on the instruction after the call completes)."""
    const = {}          # reg -> immediate value
    toff  = {4: 0}      # reg -> offset-from-this (r4 = this+0 at entry)
    pc = va; end = va + cap
    stop_at = None; reseed_at = None
    while pc < end:
        if reseed_at is not None and pc >= reseed_at:
            toff[4] = 0; const.pop(4, None); reseed_at = None
        w = r16(pc); op = (w >> 8) & 0xff; hi4 = (w >> 12) & 0xf
        t12 = (w >> 4) & 0xfff
        ri = w & 0xf; rj = (w >> 4) & 0xf; xc = (w >> 4) & 0xf
        sz = 2; wrote = None
        # --- calls: return value (this, for a ctor's alloc) lands in r4 ------
        if t12 == 0x971 or t12 == 0x9F1 or (w >> 11) == 0x1A or (w >> 11) == 0x1B:
            reseed_at = pc + (4 if (t12 == 0x9F1 or (w >> 11) == 0x1B) else 2)
            pc += sz; continue
        # --- memory accesses -------------------------------------------------
        if op in STORE or op in LOAD:
            width = STORE.get(op, LOAD.get(op))
            if op in INDEXED:                       # EA = r13 + rj
                foff = None
                if 13 in toff and rj in const:   foff = toff[13] + const[rj]
                elif rj in toff and 13 in const: foff = toff[rj] + const[13]
                if foff is not None and foff >= 0:
                    yield foff, width, op in STORE
            else:                                   # @rj, EA = rj
                if rj in toff:
                    yield toff[rj], width, op in STORE
            # loads write ri; stores write nothing
            if op in LOAD: wrote = ri
        # --- immediates ------------------------------------------------------
        elif hi4 == 0xC:                            # ldi:8 #imm,ri
            const[ri] = (w >> 4) & 0xff; toff.pop(ri, None); wrote = ri
        elif op == 0x9B:                            # ldi:20
            xl = r16(pc + 2); const[ri] = ((xc << 16) | xl) & 0xfffff; toff.pop(ri, None); sz = 4; wrote = ri
        elif (w >> 4) & 0xfff == 0x9F8:             # ldi:32
            const[ri] = struct.unpack(">I", FW[pc + 2 - BASE:pc + 6 - BASE])[0]; toff.pop(ri, None); sz = 6; wrote = ri
        # --- moves / arithmetic that carry this-ness -------------------------
        elif op == 0x8B:                            # mov rj,ri
            wrote = ri
            if rj in toff: toff[ri] = toff[rj]
            else: toff.pop(ri, None)
            if rj in const: const[ri] = const[rj]
            else: const.pop(ri, None)
        elif op in (0xA0, 0xA4):                    # addn/add #u4,ri
            wrote = ri
            if ri in toff: toff[ri] += xc
            if ri in const: const[ri] += xc
        elif op in (0xA1, 0xA5):                    # addn2/add2 #(-16+u4),ri
            wrote = ri
            if ri in toff: toff[ri] += (xc - 16)
            if ri in const: const[ri] += (xc - 16)
        elif op in (0xA2, 0xA6):                    # addn/add rj,ri
            wrote = ri
            nt = nc = None
            if ri in toff and rj in const: nt = toff[ri] + const[rj]
            elif rj in toff and ri in const: nt = toff[rj] + const[ri]
            if ri in const and rj in const: nc = const[ri] + const[rj]
            toff.pop(ri, None); const.pop(ri, None)
            if nt is not None: toff[ri] = nt
            if nc is not None: const[ri] = nc
        # --- control flow: stop at first return (after delay slot) -----------
        elif w in (0x9720, 0x9730) or (w >> 4) & 0xfff in (0x970,):   # ret / reti / jmp @ri
            stop_at = pc + 2
        elif w == 0x9F20 or (w >> 4) & 0xfff == 0x9F0:                # ret:d / jmp:d (delay slot)
            stop_at = pc + 4
        else:
            # any other op with ri as destination clobbers it (conservative)
            if hi4 in (0x2, 0x4, 0x6) or op in (0xB0,0xB1,0xB2,0xB4,0xB5,0xB6,0xB8,0x82,0x92,0x9A,0xAC,0xAE,0x97):
                wrote = ri
        if wrote is not None and op not in STORE and op not in LOAD and hi4 != 0xC \
           and op not in (0x8B,0xA0,0xA4,0xA1,0xA5,0xA2,0xA6,0x9B) and ((w>>4)&0xfff) != 0x9F8:
            const.pop(wrote, None); toff.pop(wrote, None)
        pc += sz
        if stop_at is not None and pc >= stop_at:
            break

# ---------------------------------------------------------------- source maps
HDR = re.compile(r'@k10d\s+([A-Za-z0-9_]+)\s+@\s+0x([0-9a-fA-F]+)')
def file_va_name():
    """[(path, va, name)] for every cpu/src function."""
    out = []
    for f in glob.glob(os.path.join(ROOT, "cpu/src", "*", "*.c")):
        m = HDR.search(open(f, errors="ignore").read(400))
        if m: out.append((f, int(m.group(2), 16), m.group(1)))
    return out

TYPEDEF = re.compile(r'typedef struct (cls_[0-9a-fA-F]+)\s*\{(.*?)\}\s*\1\s*;', re.S)
MEMBER  = re.compile(r'([A-Za-z_][\w ]*?[A-Za-z_])\s+(\w+)\s*(?:\[\s*(0x[0-9a-fA-F]+|\d+)\s*\])?\s*;')
WIDTH_OF = {"uint8_t": 8, "uint16_t": 16, "uint32_t": 32,
            "int8_t": 8, "int16_t": 16, "int32_t": 32, "char": 8, "short": 16, "int": 32}
TYPE_OF  = {8: "uint8_t", 16: "uint16_t", 32: "uint32_t"}

def struct_members(body):
    """Ordered [{off,name,type,nbytes,is_pad}] for EVERY member (fields of any name + explicit
    _pad arrays), offsets accumulated so arbitrary field names (field_0xNN AND field14_0xNN) and
    existing padding are preserved verbatim on rebuild."""
    out = []; off = 0
    for ty, nm, arr in MEMBER.findall(body):
        ty = ty.strip()
        unit = WIDTH_OF.get(ty, 32) // 8
        n = (int(arr, 0) if arr else 1)
        nbytes = unit * n
        out.append({"off": off, "name": nm, "type": ty, "nbytes": nbytes,
                    "is_pad": "pad" in nm, "arr": arr})
        off += nbytes
    return out

def ctor_dtor_for(classes):
    """{cls -> (ctor_va|None, dtor_va|None)}. The constructor (`cls_<vt>_new`) establishes the real
    object layout, so it is the AUTHORITATIVE width source; the destructor (`cls_<vt>_delete`)
    corroborates. Propagated-type consumers are deliberately NOT used for width decisions -- a
    mis-propagated or base-class pointer accessing a different layout would poison a narrowing."""
    byname = {n: va for _, va, n in file_va_name()}
    out = {}
    for c in classes:
        out[c] = (byname.get(c + "_new"), byname.get(c + "_delete"))
    return out

# ---------------------------------------------------------------- reconcile
FIELD_REF = re.compile(r'\bfield_0x([0-9a-fA-F]+)\b')
def protected_offsets(classes):
    """{cls -> set(offsets)} field offsets referenced in source where the class is genuinely `this`:
    its own member files (cls_<vt>_*) and functions whose param_1 resolves to the class. Used so a
    widening never absorbs a field the code still reads/writes separately."""
    byfile = {c: set() for c in classes}
    files_for = {c: set() for c in classes}
    for f, va, n in file_va_name():
        for c in classes:
            if n.startswith(c + "_") or n == c:
                files_for[c].add(f)
    if os.path.exists(RESOLVED):
        res = json.load(open(RESOLVED))
        byname_file = {n: f for f, va, n in file_va_name()}
        for fn, pmap in res.items():
            c = pmap.get("0")
            if c in files_for and fn in byname_file:
                files_for[c].add(byname_file[fn])
    for c, fs in files_for.items():
        for f in fs:
            for h in FIELD_REF.findall(open(f, errors="ignore").read()):
                byfile[c].add(int(h, 16))
    return byfile

def firmware_widths(classes):
    """{cls -> {offset -> width_bits}} from the original firmware, constructor-authoritative.
    A field's width = the width the CONSTRUCTOR accesses that offset with (the layout-defining
    store). The destructor fills in offsets the ctor never touches. Offsets where ctor and dtor
    DISAGREE are dropped (ambiguous: union/overlap) and reported, never silently corrected."""
    cd = ctor_dtor_for(classes)
    out = {}; conflicts = {}
    for c, (ctor, dtor) in cd.items():
        w = {}; conf = []
        ctor_w = {}
        if ctor:
            for off, width, is_st in probe_this_accesses(ctor):
                if off not in ctor_w or width > ctor_w[off]:
                    ctor_w[off] = width
        dtor_w = {}
        if dtor:
            for off, width, is_st in probe_this_accesses(dtor):
                if off not in dtor_w or width > dtor_w[off]:
                    dtor_w[off] = width
        for off, width in ctor_w.items():
            if off in dtor_w and dtor_w[off] != width:
                conf.append((off, width, dtor_w[off]))      # ctor vs dtor disagree -> skip
            else:
                w[off] = width
        for off, width in dtor_w.items():                    # dtor-only offsets
            if off not in ctor_w:
                w[off] = width
        out[c] = w
        if conf: conflicts[c] = conf
    out["__conflicts__"] = conflicts
    return out

def _emit(m):
    """one struct member line, preserving its exact name and array form."""
    if m.get("arr"):
        return f"  {m['type']} {m['name']}[{m['arr']}];"
    return f"  {m['type']} {m['name']};"

def rebuild_struct(name, members, fw_w, protected=frozenset()):
    """SURGICAL retype: change only the corrected field's type and absorb/insert the adjacent
    explicit padding to keep every following member at its offset. Every other member (its name
    and type, including field14_0xNN and _pad_0xNN) is preserved verbatim. A WIDEN that would have
    to absorb a `protected` (source-referenced) non-pad field is skipped and reported.
    Returns (new_lines, changes{off:(ow,nw)}, skipped{off:(ow,nw,[absorbed])})."""
    ms = [dict(m) for m in members]
    by_off = {m["off"]: i for i, m in enumerate(ms) if not m["is_pad"]}
    changes = {}; skipped = {}; drop = set()
    for o in sorted(fw_w):
        if o not in by_off:
            continue                                   # firmware offset isn't a declared field start
        i = by_off[o]; m = ms[i]
        old_w = m["nbytes"] * 8; new_w = fw_w[o]
        if new_w == old_w or new_w not in TYPE_OF:
            continue
        if new_w > old_w:                              # WIDEN: consume following bytes
            need = (new_w - old_w) // 8
            j = i + 1; consumed = []; absorbs = []; ok = True
            while need > 0 and j < len(ms):
                nx = ms[j]
                if nx["is_pad"]:
                    if nx["nbytes"] <= need:
                        need -= nx["nbytes"]; consumed.append(j); j += 1
                    else:                              # shrink the pad array
                        rem = nx["nbytes"] - need
                        ms[j] = dict(nx, nbytes=rem, arr=hex(rem), name=f"_pad_0x{nx['off']+need:x}")
                        need = 0
                else:                                  # a real field
                    if nx["off"] in protected:
                        absorbs.append(nx["off"]); ok = False; break
                    if nx["nbytes"] <= need:
                        need -= nx["nbytes"]; consumed.append(j); j += 1
                    else:
                        ok = False; break
            if not ok or need != 0:
                skipped[o] = (old_w, new_w, absorbs or ["misaligned"]); continue
            m["type"] = TYPE_OF[new_w]; m["nbytes"] = new_w // 8; m["arr"] = None
            drop.update(consumed); changes[o] = (old_w, new_w)
        else:                                          # NARROW: retype + insert pad for freed bytes
            freed = (old_w - new_w) // 8
            m["type"] = TYPE_OF[new_w]; m["nbytes"] = new_w // 8; m["arr"] = None
            padoff = o + new_w // 8
            m["_pad_after"] = {"type": "uint8_t", "name": f"_pad_0x{padoff:x}",
                               "arr": hex(freed) if freed > 1 else "0x1", "nbytes": freed, "is_pad": True, "off": padoff}
            changes[o] = (old_w, new_w)
    lines = []
    for i, m in enumerate(ms):
        if i in drop:
            continue
        lines.append(_emit(m))
        if "_pad_after" in m:
            lines.append(_emit(m["_pad_after"]))
    return lines, changes, skipped

def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--class", dest="classes", action="append", default=[])
    ap.add_argument("--all", action="store_true")
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    txt = open(STRUCTS, errors="ignore").read()
    defs = {m.group(1): (m.group(0), m.group(2)) for m in TYPEDEF.finditer(txt)}
    if a.all:
        classes = list(defs)
    elif a.classes:
        classes = a.classes
    else:
        classes = FLAGGED
    classes = [c for c in classes if c in defs]
    fw = firmware_widths(classes)
    conflicts = fw.pop("__conflicts__", {})
    prot = protected_offsets(classes)
    new_text = txt; total_changes = 0; touched_classes = []; all_skipped = {}
    for c in classes:
        whole, body = defs[c]
        members = struct_members(body)
        if not fw[c]:
            continue
        lines, changes, skipped = rebuild_struct(c, members, fw[c], prot.get(c, frozenset()))
        if skipped:
            all_skipped[c] = skipped
        if not changes:
            continue
        touched_classes.append(c)
        total_changes += len(changes)
        print(f"\n{c}: {len(changes)} field(s) corrected from firmware access widths")
        for o in sorted(changes):
            ow, nw = changes[o]
            print(f"  0x{o:<4x} {ow:>2}b -> {nw:>2}b  ({TYPE_OF.get(ow,'?')} -> {TYPE_OF[nw]})")
        new_whole = f"typedef struct {c} {{\n" + "\n".join(lines) + f"\n}} {c};"
        new_text = new_text.replace(whole, new_whole)
    if all_skipped:
        print("\n---- SKIPPED (widen would absorb a source-referenced field; needs manual review) ----")
        for c, sk in all_skipped.items():
            for o, (ow, nw, absorbs) in sk.items():
                print(f"  {c} 0x{o:x}: {ow}b->{nw}b would absorb referenced {[hex(b) for b in absorbs]}")
    if conflicts:
        print("\n---- ctor/dtor WIDTH CONFLICTS (ambiguous, NOT auto-corrected) ----")
        for c, cs in conflicts.items():
            for off, cw, dw in cs:
                print(f"  {c} 0x{off:x}: ctor {cw}b vs dtor {dw}b")
    print(f"\n==== {total_changes} field corrections across {len(touched_classes)} classes ====")
    if a.write and total_changes:
        open(STRUCTS, "w").write(new_text)
        print(f"wrote {STRUCTS}")
        # structs.h is a shared header but the incremental build keys on .c mtime, so touch EVERY
        # cpu/src .c that references a changed class, forcing those translation units to rebuild.
        names = "|".join(re.escape(c) for c in touched_classes)
        pat = re.compile(r'\b(' + names + r')\b')
        touched = 0
        for f in glob.glob(os.path.join(ROOT, "cpu/src", "*", "*.c")):
            if pat.search(open(f, errors="ignore").read()):
                os.utime(f, None); touched += 1
        print(f"touched {touched} .c files referencing the changed classes (forces rebuild)")
    elif a.write:
        print("no changes to write")

if __name__ == "__main__":
    main()
